/**
 * @file Link bridge
 * @description Routes "open this URL" requests from programs inside PersaLink
 *   sessions to the device viewing the session. This box is headless: when
 *   Claude Code (or gh, python's webbrowser, …) opens a link it would run
 *   xdg-open here, where there is no screen — so Ctrl-click on a link did
 *   nothing at all. PersaLink sessions get $BROWSER pointed at a tiny shim
 *   that drops the URL into a spool directory; this module watches the spool
 *   and hands each request to the server, which shows an "Open link" prompt
 *   on the clients attached to that session.
 *
 *   The spool is a 0700 directory, so only this user's processes can submit —
 *   no network endpoint, no shared secret. URLs are validated (http/https
 *   only) before they leave the server.
 */

import * as fs from 'fs';
import * as path from 'path';
import { CONFIG_DIR } from './config';

export const OPEN_DIR = path.join(CONFIG_DIR, 'open-requests');
export const SHIM_PATH = path.join(CONFIG_DIR, 'bin', 'persalink-open');

const MAX_URL_LENGTH = 4096;
/** Requests older than this are stale (server was down) — never replayed. */
const MAX_AGE_MS = 60_000;
/** A runaway process can't flood clients with prompts. */
const MAX_PER_DRAIN = 10;

const SHIM = `#!/bin/sh
# PersaLink link bridge — installed as $BROWSER inside PersaLink tmux sessions.
# Hands each URL to the PersaLink server, which shows an "Open link" prompt on
# the device viewing this session. Generated by the server; edits are replaced.
dir="\${PERSALINK_OPEN_DIR:-$HOME/.persalink/open-requests}"
[ -d "$dir" ] || exit 1
sess=""
if [ -n "$TMUX_PANE" ]; then
  sess=$(tmux display-message -p -t "$TMUX_PANE" '#{session_name}' 2>/dev/null)
fi
for url in "$@"; do
  tmp=$(mktemp "$dir/.req.XXXXXX") || exit 1
  printf '%s\\n%s\\n' "$sess" "$url" > "$tmp" || { rm -f "$tmp"; exit 1; }
  base=\${tmp##*/}
  mv "$tmp" "$dir/\${base#.}" || exit 1
done
exit 0
`;

export interface OpenRequest {
  /** tmux session the request came from (null when not from a pl- session). */
  sessionId: string | null;
  url: string;
}

/** Validate a URL from the spool. Only absolute http(s) URLs leave the server. */
export function parseOpenRequest(content: string): OpenRequest | null {
  const [sessionLine = '', urlLine = ''] = content.split('\n');
  const url = urlLine.trim();
  if (!url || url.length > MAX_URL_LENGTH) return null;
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
  } catch {
    return null;
  }
  const session = sessionLine.trim();
  return { sessionId: /^pl-[A-Za-z0-9._-]+$/.test(session) ? session : null, url };
}

/** Environment every PersaLink session gets so its programs use the bridge. */
export function linkBridgeEnv(): Record<string, string> {
  return {
    BROWSER: SHIM_PATH,
    PERSALINK_OPEN_DIR: OPEN_DIR,
    // Ask CLIs (Claude Code included) to emit OSC 8 hyperlinks: a link
    // wrapped across rows stays ONE clickable link in xterm.js.
    FORCE_HYPERLINK: '1',
  };
}

export class LinkBridge {
  private watcher: fs.FSWatcher | null = null;
  private drainTimer: ReturnType<typeof setTimeout> | null = null;

  constructor(private readonly onRequest: (req: OpenRequest) => void) {}

  /** Create the spool + shim (idempotent) and start watching. */
  start(): void {
    fs.mkdirSync(OPEN_DIR, { recursive: true, mode: 0o700 });
    fs.chmodSync(OPEN_DIR, 0o700);
    fs.mkdirSync(path.dirname(SHIM_PATH), { recursive: true, mode: 0o700 });
    let current = '';
    try { current = fs.readFileSync(SHIM_PATH, 'utf-8'); } catch { /* first run */ }
    if (current !== SHIM) fs.writeFileSync(SHIM_PATH, SHIM, { mode: 0o700 });
    fs.chmodSync(SHIM_PATH, 0o700);

    // Requests left from before a restart have no client to go to — drop them.
    this.drain(true);
    this.watcher = fs.watch(OPEN_DIR, () => this.scheduleDrain());
    this.watcher.on('error', (err) => console.warn('[PersaLink] link bridge watch error:', err.message));
  }

  dispose(): void {
    this.watcher?.close();
    this.watcher = null;
    if (this.drainTimer) clearTimeout(this.drainTimer);
  }

  private scheduleDrain(): void {
    if (this.drainTimer) return;
    this.drainTimer = setTimeout(() => {
      this.drainTimer = null;
      this.drain();
    }, 30);
  }

  private drain(discard = false): void {
    let names: string[];
    try {
      names = fs.readdirSync(OPEN_DIR).filter((n) => !n.startsWith('.'));
    } catch {
      return;
    }
    let delivered = 0;
    let dropped = 0;
    const now = Date.now();
    for (const name of names) {
      const file = path.join(OPEN_DIR, name);
      let content = '';
      let fresh = false;
      try {
        const st = fs.lstatSync(file);
        fresh = st.isFile() && now - st.mtimeMs < MAX_AGE_MS && st.size <= MAX_URL_LENGTH + 512;
        if (fresh) content = fs.readFileSync(file, 'utf-8');
      } catch { /* raced with another drain */ }
      try { fs.unlinkSync(file); } catch { /* already gone */ }
      if (discard || !fresh) continue;
      const req = parseOpenRequest(content);
      if (!req) continue;
      if (delivered >= MAX_PER_DRAIN) { dropped++; continue; }
      delivered++;
      this.onRequest(req);
    }
    if (dropped > 0) console.warn(`[PersaLink] link bridge: dropped ${dropped} open request(s) over the per-burst cap`);
  }
}
